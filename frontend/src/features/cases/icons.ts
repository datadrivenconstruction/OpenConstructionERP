/** Resolve a playbook/step icon name to its glyph; Sparkles for the unknown. */
export function iconFor(name: string | undefined): ComponentType<LucideProps> {
  if (name && name in ICON_MAP) return ICON_MAP[name]!;
  return Sparkles;
}
