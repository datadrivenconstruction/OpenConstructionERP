def base_language(locale: str | None) -> str:
    """Return the lower-case base language of a locale tag (``"pt-BR"`` -> ``"pt"``)."""
    return (locale or "").replace("_", "-").split("-")[0].strip().lower() or FALLBACK_LANGUAGE


def resource_name(key: str, locale: str | None) -> str:
    """Return the display name of one resource key in the project's language.

    Args:
        key: The stable resource key the generator wrote on the row.
        locale: The demo template's locale tag; ``None`` or an unknown
            language reads English.

    Returns:
        The localised name, the English one when the language or the key is
        missing, and the key itself only for a key no table knows, so a typo
        surfaces on screen instead of as an empty cell.
    """
    table = RESOURCE_NAMES.get(base_language(locale)) or {}
    return table.get(key) or RESOURCE_NAMES[FALLBACK_LANGUAGE].get(key) or key
