def _is_future(value: Any) -> bool:
    """Whether a date or datetime is after now, comparing like with like."""
    if isinstance(value, datetime):
        from datetime import UTC

        now = datetime.now(UTC)
        # A naive datetime cannot be compared with an aware one, and which of
        # the two arrives depends on the client rather than on this module.
        if value.tzinfo is None:
            value = value.replace(tzinfo=UTC)
        return value > now
    if isinstance(value, date):
        from datetime import UTC

        return value > datetime.now(UTC).date()
    return False


