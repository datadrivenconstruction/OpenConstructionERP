def _init(spec: ModuleSpec) -> str:
    """The package, and the startup hook the loader calls after importing it.

    Two things have to happen once the module is loaded and neither can happen
    at import time. Permissions must be registered, because a permission the
    registry has never heard of is denied to everyone except an administrator,
    and the module would then appear to work for whoever tested it and for
    nobody else. And the table has to exist, because a module installed at
    runtime has no migration to create it.
    """
