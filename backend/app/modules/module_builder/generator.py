def _locale(spec: ModuleSpec) -> str:
    """English strings for the generated screen.

    English only, on purpose. The platform ships 29 locales and a machine
    translation nobody read is worse than an untranslated string: the reader
    cannot tell it was never checked. The generated screen falls back to
    English until a person translates it.
    """
    payload = {
        spec.key: {
            "title": spec.display_name,
            "description": spec.description,
            "entity": spec.entity.display_name,
            "entityPlural": spec.entity.plural_name,
            "fields": {f.name: f.label for f in spec.entity.fields},
            "help": {f.name: f.help_text for f in spec.entity.fields if f.help_text},
            "rules": {r.code: r.message for r in spec.rules},
        }
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


