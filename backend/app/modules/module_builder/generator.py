def _tests(spec: ModuleSpec) -> str:
    """Tests that come with the module, exercising its own rules.

    Generated from the same rules the validator was generated from, so they
    check the rendering rather than restating it: each one builds a record that
    breaks exactly one rule and asserts that rule fires.
    """
    cases = []
    for rule in spec.rules:
        cases.append(
            f"    def test_{rule.code.lower()}_fires(self) -> None:\n"
            f"        findings = validate(_breaking({rule.code!r}))\n"
            f"        assert {rule.code!r} in [f.code for f in findings]\n"
        )
    field_defaults = ", ".join(f"{f.name}={_sample_source(f)}" for f in spec.entity.fields)
    return f'''{HEADER}"""Tests for {spec.display_name}."""

{GENERATED_NOTE}
from datetime import UTC, datetime, timedelta  # noqa: F401
from types import SimpleNamespace

from app.modules.{spec.key}.validators import validate

RULES = {[r.model_dump(mode="json") for r in spec.rules]!r}


def _sound() -> SimpleNamespace:
    """A record every rule accepts."""
    return SimpleNamespace({field_defaults})


def _breaking(code: str) -> SimpleNamespace:
    """A sound record with exactly one rule broken."""
    record = _sound()
    rule = next(r for r in RULES if r["code"] == code)
    field, kind = rule["field"], rule["kind"]
    if kind == "required":
        setattr(record, field, None)
    elif kind in {{"positive"}}:
        setattr(record, field, -1)
    elif kind == "range":
        low, high = rule.get("min_value"), rule.get("max_value")
        setattr(record, field, (low - 1) if low is not None else (high + 1))
    elif kind == "one_of":
        setattr(record, field, "definitely-not-an-option")
    elif kind == "not_future":
        # No local import here. Binding datetime names inside one branch makes
        # them local to the whole function, and the order branch below then
        # raises UnboundLocalError on a name the module already imported.
        current = getattr(record, field)
        ahead = datetime.now(UTC) + timedelta(days=365)
        setattr(record, field, ahead if isinstance(current, datetime) else ahead.date())
    elif kind == "order":
        # One day past the field it must not exceed.
        setattr(record, field, getattr(record, rule["other_field"]) + timedelta(days=1))
    return record


class TestRules:
    def test_a_sound_record_passes_every_rule(self) -> None:
        assert validate(_sound()) == []

{chr(10).join(cases)}
    def test_every_rule_is_covered(self) -> None:
        """The count is the point: a rule with no test looks the same as one that passes."""
        tested = {{name.removeprefix("test_").removesuffix("_fires").upper() for name in dir(TestRules) if name.endswith("_fires")}}
        assert tested == {{r["code"] for r in RULES}}
'''


def _sample_source(field: FieldSpec) -> str:
    """Python source for a value every rule accepts.

    Source rather than a value: a date has no literal form that ``repr`` can
    put in a generated file, and a placeholder string in its place would give
    the generated tests a record that fails on a type error rather than on the
    rule under test.

    Numbers start at 1 so a ``positive`` rule holds; a ``range`` rule can still
    exclude 1, which the range case in ``_breaking`` accounts for by moving
    outside the bound rather than assuming the sound value is inside it.
    """
    if field.type == "integer":
        return "1"
    if field.type in {"number", "money"}:
        return "1"
    if field.type == "boolean":
        return "True"
    # Yesterday, not today: it satisfies ``not_future`` without depending on
    # the clock crossing midnight mid-run, and leaves room for an ``order``
    # rule to place a later field after it.
    if field.type == "date":
        return "(datetime.now(UTC) - timedelta(days=2)).date()"
    if field.type == "datetime":
        return "datetime.now(UTC) - timedelta(days=2)"
    if field.type == "select":
        return repr(field.options[0])
    if field.type == "long_text":
        return repr(f"About {field.label.lower()}")
    return repr(field.label)


