"""Catalogue of event names a webhook can subscribe to.

The names are the ones modules publish on the event bus. The committed
``event_catalogue.json`` is generated by ``scripts/gen_event_catalogue.py``;
names with a live subscriber on the bus are added at runtime, so an event a
plug-in module introduces shows up without regenerating the file.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from functools import lru_cache
from pathlib import Path

WILDCARD = "*"
I18N_PREFIX = "developer.event."

_FILE = Path(__file__).with_name("event_catalogue.json")


@lru_cache(maxsize=1)
def _generated() -> frozenset[str]:
    try:
        return frozenset(json.loads(_FILE.read_text(encoding="utf-8")))
    except (OSError, ValueError):
        return frozenset()


def event_names() -> list[str]:
    """Every subscribable event name, sorted."""
    names = set(_generated())
    try:
        from app.core.events import event_bus

        names.update(n for n in event_bus.list_handlers() if WILDCARD not in n)
    except Exception:  # noqa: BLE001 - the file alone is a valid catalogue
        pass
    return sorted(names)


def catalogue() -> list[dict[str, str]]:
    """Rows for ``GET /webhooks/events/``: name, owning module and an i18n key for the label."""
    return [{"name": n, "module": n.split(".", 1)[0], "i18n_key": f"{I18N_PREFIX}{n}"} for n in event_names()]


def unknown_events(events: Iterable[str]) -> list[str]:
    """The entries of ``events`` that are neither ``*`` nor a catalogued name."""
    known = set(event_names())
    return sorted({e for e in events if e != WILDCARD and e not in known})
