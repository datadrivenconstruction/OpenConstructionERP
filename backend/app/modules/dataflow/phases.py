PHASE_OF: dict[str, str] = {module: phase for phase, modules in _TABLE.items() for module in modules}


def phase_of(name: str, manifest: Any) -> str:
    """Phase of a module: its declaration's ``phase``, else the table, else ``platform``."""
    decl = getattr(manifest, "data_paths", None)
    own = getattr(decl, "phase", "") if decl is not None else ""
    if own in PHASES:
        return own
    return PHASE_OF.get(name.removeprefix("oe_"), "platform")
