"""Rules a payable invoice meets before it is approved, rule set ``invoice_posting``.

* ``invoice_posting.within_commitment`` - ERROR. An invoice linked to a
  purchase order or subcontract agreement bills no more than is still open on
  it: the commitment plus its approved changes, less what the other invoices on
  it already billed, net of VAT, within the order's invoice tolerance. The only
  way past it is an approved change that raises the commitment.
* ``invoice_posting.commitment_currency`` - ERROR. The invoice is in the
  commitment's currency; an amount in another currency cannot be weighed
  against it, and no rate is guessed.
* ``invoice_posting.commitment_retention`` - WARNING. Where the commitment
  agrees retention, the invoice holds back at least that share of its net.
* ``invoice_posting.duplicate_number`` - ERROR. The same supplier's invoice
  number is entered once, on any project. System-generated numbers are not
  the supplier's and are not compared.
* ``invoice_posting.possible_duplicate`` - WARNING. The same supplier, total
  and date under another number is pointed out.
* ``invoice_posting.payment_date_before_invoice`` - ERROR. A payment cannot
  be scheduled before the invoice date.

Each rule reads ``context.data["invoice_posting"]`` (built by
``FinanceService.posting_payload``) and is silent on any other data. Receivables
are not checked. The checks are pure functions, so tests and the read-only
endpoint give the same answer as the approval gate.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation
from typing import Any

from app.core.currency_registry import sentence_amount
from app.core.validation.engine import RuleCategory, RuleResult, Severity, ValidationContext, ValidationRule
from app.core.validation.messages import DEFAULT_LOCALE, translate

RULE_SET = "invoice_posting"
PAYLOAD_KEY = "invoice_posting"

_ZERO = Decimal("0")
_CENT = Decimal("0.01")

#: Numbers ``InvoiceRepository.next_invoice_number`` writes (``INV-P-001``,
#: ``DE01-INV-P-001``). They are ours, not the supplier's, so they say nothing
#: about a duplicate.
_GENERATED_NUMBER = re.compile(r"^([A-Z0-9]+-)?INV-[PR]-\d+$", re.IGNORECASE)


def normalise_number(raw: object) -> str:
    """How two invoice numbers are compared: case, spaces and separators ignored."""
    return re.sub(r"[\s\-_/.]", "", str(raw or "")).casefold()


def is_generated_number(raw: object) -> bool:
    """Whether the number was generated by the platform rather than written by the supplier."""
    return bool(_GENERATED_NUMBER.match(str(raw or "").strip()))


def _dec(raw: object) -> Decimal:
    try:
        parsed = Decimal(str(raw if raw not in (None, "") else "0"))
    except (InvalidOperation, ValueError, TypeError):
        return _ZERO
    return parsed if parsed.is_finite() else _ZERO


@dataclass(frozen=True)
class Finding:
    """One failure: the message parameters and the machine-readable details."""

    params: dict[str, Any]
    details: dict[str, Any] = field(default_factory=dict)


def _ref(payload: dict[str, Any]) -> str:
    return str(payload.get("invoice_number") or "").strip() or "-"


def _commitment(payload: dict[str, Any]) -> dict[str, Any] | None:
    commitment = payload.get("commitment")
    return commitment if isinstance(commitment, dict) else None


def _payable(payload: dict[str, Any]) -> bool:
    return str(payload.get("invoice_direction") or "payable") == "payable"


def _same_currency(payload: dict[str, Any], commitment: dict[str, Any]) -> bool:
    invoice = str(payload.get("currency_code") or "").strip().upper()
    committed = str(commitment.get("currency_code") or "").strip().upper()
    return not invoice or not committed or invoice == committed


def check_within_commitment(payload: dict[str, Any]) -> list[Finding]:
    """The invoice's net stays within what is still open on its commitment."""
    commitment = _commitment(payload)
    if not _payable(payload) or commitment is None or not _same_currency(payload, commitment):
        return []
    currency = str(commitment.get("currency_code") or "")
    revised = _dec(commitment.get("original")) + _dec(commitment.get("approved_changes"))
    remaining = revised - _dec(commitment.get("invoiced"))
    invoice = _dec(payload.get("amount_subtotal"))
    band = max(_dec(commitment.get("tolerance")), _CENT)
    if invoice <= remaining + band:
        return []
    open_now = max(remaining, _ZERO)
    return [
        Finding(
            params={
                "invoice": _ref(payload),
                "commitment": str(commitment.get("ref") or ""),
                "remaining": sentence_amount(open_now, currency),
                "excess": sentence_amount(invoice - open_now, currency),
            },
            details={
                "commitment_kind": commitment.get("kind"),
                "revised_net": str(revised),
                "invoiced_before_net": str(_dec(commitment.get("invoiced"))),
                "remaining_net": str(remaining),
                "invoice_net": str(invoice),
                "tolerance_net": str(band),
            },
        )
    ]


def check_commitment_currency(payload: dict[str, Any]) -> list[Finding]:
    """The invoice is in the currency of the commitment it bills."""
    commitment = _commitment(payload)
    if not _payable(payload) or commitment is None or _same_currency(payload, commitment):
        return []
    return [
        Finding(
            params={
                "invoice": _ref(payload),
                "commitment": str(commitment.get("ref") or ""),
                "invoice_currency": str(payload.get("currency_code") or "").upper(),
                "commitment_currency": str(commitment.get("currency_code") or "").upper(),
            }
        )
    ]


def check_commitment_retention(payload: dict[str, Any]) -> list[Finding]:
    """Where the commitment agrees retention, the invoice holds back at least its share."""
    commitment = _commitment(payload)
    if not _payable(payload) or commitment is None or commitment.get("retain_on_receipt"):
        return []
    percent = _dec(commitment.get("retention_percent"))
    if percent <= 0:
        return []
    net = _dec(payload.get("amount_subtotal"))
    expected = (net * percent / Decimal("100")).quantize(_CENT)
    held = _dec(payload.get("retention_amount"))
    if held + _CENT >= expected:
        return []
    currency = str(commitment.get("currency_code") or payload.get("currency_code") or "")
    return [
        Finding(
            params={
                "invoice": _ref(payload),
                "commitment": str(commitment.get("ref") or ""),
                "retention": sentence_amount(held, currency),
                "expected": sentence_amount(expected, currency),
                "percent": f"{percent.normalize():f}",
            },
            details={"expected_retention": str(expected), "retention_amount": str(held)},
        )
    ]


def check_duplicate_number(payload: dict[str, Any]) -> list[Finding]:
    """The supplier's invoice number is not already entered on another invoice of theirs."""
    if not _payable(payload) or not payload.get("contact_id"):
        return []
    number = payload.get("invoice_number")
    if not normalise_number(number) or is_generated_number(number):
        return []
    clashes = [str(n) for n in payload.get("same_number") or []]
    if not clashes:
        return []
    return [Finding(params={"invoice": _ref(payload)}, details={"other_invoice_ids": clashes})]


def check_possible_duplicate(payload: dict[str, Any]) -> list[Finding]:
    """Another invoice of the same supplier carries the same total on the same date."""
    if not _payable(payload) or not payload.get("contact_id"):
        return []
    others = [str(n) for n in payload.get("same_amount_date") or []]
    if not others:
        return []
    return [
        Finding(
            params={
                "invoice": _ref(payload),
                "other": ", ".join(others[:3]),
                "amount": sentence_amount(_dec(payload.get("amount_total")), str(payload.get("currency_code") or "")),
                "on": str(payload.get("invoice_date") or ""),
            },
            details={"other_invoice_numbers": others},
        )
    ]


def check_payment_date_before_invoice(payload: dict[str, Any]) -> list[Finding]:
    """A payment is not scheduled before the invoice is dated."""
    scheduled = str(payload.get("scheduled_payment_date") or "")[:10]
    invoice_date = str(payload.get("invoice_date") or "")[:10]
    if not _payable(payload) or not scheduled or not invoice_date or scheduled >= invoice_date:
        return []
    return [Finding(params={"scheduled": scheduled, "invoice_date": invoice_date})]


class _PostingRule(ValidationRule):
    """Run one pure check over the ``invoice_posting`` payload and translate its findings."""

    standard = "finance"
    check_name: str = ""

    async def validate(self, context: ValidationContext) -> list[RuleResult]:
        data = context.data
        payload = data.get(PAYLOAD_KEY) if isinstance(data, dict) else None
        if not isinstance(payload, dict):
            return []
        meta = getattr(context, "metadata", None) or {}
        locale = str(meta.get("locale") or DEFAULT_LOCALE)
        findings: list[Finding] = globals()[self.check_name](payload)
        ref = _ref(payload)
        if not findings:
            return [
                RuleResult(
                    rule_id=self.rule_id,
                    rule_name=self.name,
                    severity=self.severity,
                    category=self.category,
                    passed=True,
                    message=translate("common.ok", locale=locale),
                    element_ref=ref,
                )
            ]
        return [
            RuleResult(
                rule_id=self.rule_id,
                rule_name=self.name,
                severity=self.severity,
                category=self.category,
                passed=False,
                message=translate(f"{self.rule_id}.fail", locale=locale, **finding.params),
                element_ref=ref,
                details=dict(finding.details),
                suggestion=translate(f"{self.rule_id}.suggestion", locale=locale),
            )
            for finding in findings
        ]


class InvoiceWithinCommitment(_PostingRule):
    rule_id = "invoice_posting.within_commitment"
    name = "Invoice Within Commitment"
    severity = Severity.ERROR
    category = RuleCategory.CONSISTENCY
    description = "Refuses an invoice whose net exceeds what is still open on its order or subcontract."
    check_name = "check_within_commitment"


class InvoiceCommitmentCurrency(_PostingRule):
    rule_id = "invoice_posting.commitment_currency"
    name = "Invoice In Commitment Currency"
    severity = Severity.ERROR
    category = RuleCategory.CONSISTENCY
    description = "Refuses an invoice in a currency other than its order's or subcontract's."
    check_name = "check_commitment_currency"


class InvoiceCommitmentRetention(_PostingRule):
    rule_id = "invoice_posting.commitment_retention"
    name = "Invoice Holds The Agreed Retention"
    severity = Severity.WARNING
    category = RuleCategory.COMPLIANCE
    description = "Flags an invoice that holds back less retention than its commitment agrees."
    check_name = "check_commitment_retention"


class InvoiceDuplicateNumber(_PostingRule):
    rule_id = "invoice_posting.duplicate_number"
    name = "Supplier Invoice Number Entered Once"
    severity = Severity.ERROR
    category = RuleCategory.CONSISTENCY
    description = "Refuses a supplier invoice number already entered for the same supplier."
    check_name = "check_duplicate_number"


class InvoicePossibleDuplicate(_PostingRule):
    rule_id = "invoice_posting.possible_duplicate"
    name = "Possible Duplicate Invoice"
    severity = Severity.WARNING
    category = RuleCategory.CONSISTENCY
    description = "Flags an invoice with the same supplier, total and date as another one."
    check_name = "check_possible_duplicate"


class InvoicePaymentDateAfterInvoice(_PostingRule):
    rule_id = "invoice_posting.payment_date_before_invoice"
    name = "Payment Scheduled After The Invoice Date"
    severity = Severity.ERROR
    category = RuleCategory.CONSISTENCY
    description = "Refuses a scheduled payment date before the invoice date."
    check_name = "check_payment_date_before_invoice"


POSTING_RULES: tuple[ValidationRule, ...] = (
    InvoiceWithinCommitment(),
    InvoiceCommitmentCurrency(),
    InvoiceCommitmentRetention(),
    InvoiceDuplicateNumber(),
    InvoicePossibleDuplicate(),
    InvoicePaymentDateAfterInvoice(),
)


def register_posting_rules() -> None:
    """Register the rules under ``invoice_posting``. Idempotent: the registry overwrites by id."""
    from app.core.validation.engine import rule_registry

    for rule in POSTING_RULES:
        rule_registry.register(rule, [RULE_SET])
