def build_insertion_lines(locale: str) -> str:
    """Build the block of 23 lines to insert."""
    values = TRANSLATIONS[locale]
    lines = []
    for key, value in zip(KEYS, values):
        # Escape any single quotes in value by using double-quoted TS strings
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{key}": "{escaped}",')
    return "\n".join(lines)


def process_file(locale: str) -> tuple[bool, str]:
    """Insert the 23 keys after timeline.showing in the given locale file.
    Returns (changed, message)."""
    path = LOCALES_DIR / f"{locale}.ts"
    if not path.exists():
        return False, f"File not found: {path}"

    text = path.read_text(encoding="utf-8")

    # Check if already present (idempotent)
    if '"timeline.total_events"' in text:
        return False, f"{locale}: already has timeline.total_events, skipping"

    # Find the timeline.showing line
    pattern = re.compile(r'("timeline\.showing":[^\n]*\n)')
    match = pattern.search(text)
    if not match:
        return False, f"{locale}: timeline.showing not found"

    insertion = build_insertion_lines(locale)
    new_text = text[: match.end()] + insertion + "\n" + text[match.end() :]
    path.write_text(new_text, encoding="utf-8")
    return True, f"{locale}: inserted 23 keys"


def main() -> None:
    required = [
        "ar", "bg", "bn", "cs", "da", "de", "el", "es", "es-CL", "es-CO", "es-MX",
        "et", "fa", "fi", "fil", "fr", "he", "hi", "hr", "hu", "id", "it", "ja",
        "kk", "ko", "ky", "mn", "nl", "no", "pl", "pt", "pt-BR", "ro", "ru", "sv",
        "th", "tr", "uk", "ur", "uz", "vi", "zh",
    ]

    missing_translations = [loc for loc in required if loc not in TRANSLATIONS]
    if missing_translations:
        print(f"ERROR: no translations defined for: {missing_translations}", file=sys.stderr)
        sys.exit(1)

    changed = 0
    for locale in required:
        ok, msg = process_file(locale)
        print(msg)
        if ok:
            changed += 1

    print(f"\nDone: {changed}/{len(required)} files updated.")


if __name__ == "__main__":
    main()
